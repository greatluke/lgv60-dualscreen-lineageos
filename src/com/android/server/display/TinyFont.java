    private TinyFont() { }

    /** Width in pixels of {@code text} at {@code scale}, including inter-character spacing. */
    static int measure(String text, int scale) {
        if (text.isEmpty()) {
            return 0;
        }
        int perChar = GLYPH_W * scale + scale; // one scaled column of spacing
        return text.length() * perChar - scale;
    }

    /**
     * Draws {@code text} into {@code buf} with its top-left at (x, y).
     * Unknown characters are skipped, so callers never need to sanitise input.
     */
    static void draw(int[] buf, int bufW, int bufH, int x, int y,
                     String text, int scale, int color) {
        int cursor = x;
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            String[] g = GLYPHS.get(c);
            if (g == null) {
                // Fall back to the uppercase form for anything we only drew once.
                g = GLYPHS.get(Character.toUpperCase(c));
            }
            if (g != null) {
                drawGlyph(buf, bufW, bufH, cursor, y, g, scale, color);
            }
            cursor += GLYPH_W * scale + scale;
        }
    }

    private static void drawGlyph(int[] buf, int bufW, int bufH, int x, int y,
                                  String[] glyph, int scale, int color) {
        for (int row = 0; row < GLYPH_H; row++) {
            String bits = glyph[row];
            for (int col = 0; col < GLYPH_W; col++) {
                if (bits.charAt(col) != '#') {
                    continue;
                }
                int px0 = x + col * scale;
                int py0 = y + row * scale;
                for (int dy = 0; dy < scale; dy++) {
                    int py = py0 + dy;
                    if (py < 0 || py >= bufH) {
                        continue;
                    }
                    int rowOff = py * bufW;
                    for (int dx = 0; dx < scale; dx++) {
                        int px = px0 + dx;
                        if (px < 0 || px >= bufW) {
                            continue;
                        }
                        buf[rowOff + px] = color;
                    }
                }
            }
        }
    }
